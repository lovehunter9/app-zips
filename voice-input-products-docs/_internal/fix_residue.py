    ("前序章节 落实", "已查证"),
    ("前序章节 中", "前文中"),
    ("前序章节 之后", "之后"),
    ("前序章节 §", "§"),
    ("前序章节", "前文相关章节"),
    # 内嵌的"对应 §10 L-*"残留
    ("对应 §10 L‑*", "对应留待事项"),
    ("对应 §10 L-*", "对应留待事项"),
